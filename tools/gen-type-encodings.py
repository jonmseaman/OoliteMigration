#!/usr/bin/env python3
"""Render the game's measured Objective-C type encodings as a C++ header (bead oo-dbz.3, ADR-0056
amendment oo-dbz.3).

The member tables (OOEntityCalledByNameTable.h, OOJSCallEntityMethods.h, EntityShaderBindings,
OOJSConsole's monitor rows) and OOShaderUniformTypeFromEncoding carried @encode() of their types:
the by-name dispatcher classifies a row by it and prints it in its "has no signature a by-name call
can use (type encoding ...)" log line. With libobjc2 gone (oo-dbz) the game is C++ and has no
@encode, so each encoding becomes the literal clang's @encode() gave on main eae8c876d, the last
tree built as Objective-C++: tools/type-encodings.tsv holds the measurement, and this script
renders upstream/oolite/src/Core/OOTypeEncodings.h from it (kOOTypeEncoding<T>, one explicit
specialisation per measured type).

    python3 tools/gen-type-encodings.py                   # rewrite the header
    python3 tools/gen-type-encodings.py --check           # exit 1 if the header is stale
    python3 tools/gen-type-encodings.py --probe X.mm      # write the measuring probe (Objective-C++)
    python3 tools/gen-type-encodings.py --compare M.tsv   # exit 1 unless a measurement matches the data

The probe prints "<spelling>\\t<encoding>" for every measured spelling; compile it with oolite.exe's
Objective-C++ flags (clang, -fobjc-runtime=gnustep-2.2, any tree that still has them) and run it to
measure again.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "tools/type-encodings.tsv"
OUT = ROOT / "upstream/oolite/src/Core/OOTypeEncodings.h"
TAGS = {"OOObjCId": "id", "OOObjCSelector": "SEL"}
PIECE = 100		# characters of an encoding per source line


def data():
    """[(key, [spellings], encoding)] in file order."""
    rows = []
    keys = set()
    spellings = set()
    for number, line in enumerate(DATA.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 3 or not all(fields):
            raise SystemExit(f"{DATA.name}:{number}: want key<TAB>spellings<TAB>encoding")
        key, names, encoding = fields
        names = [n.strip() for n in names.split(",")]
        if key in keys:
            raise SystemExit(f"{DATA.name}:{number}: key {key!r} twice")
        keys.add(key)
        for n in names:
            if n in spellings:
                raise SystemExit(f"{DATA.name}:{number}: spelling {n!r} twice")
            spellings.add(n)
        if key in TAGS and names != [TAGS[key]]:
            raise SystemExit(f"{DATA.name}:{number}: {key} is the key of {TAGS[key]} alone")
        if any(c in encoding for c in "\"\\\n"):
            raise SystemExit(f"{DATA.name}:{number}: an encoding with a quote or backslash is not handled")
        rows.append((key, names, encoding))
    return rows


def literal(encoding):
    pieces = [encoding[i:i + PIECE] for i in range(0, len(encoding), PIECE)] or [""]
    if len(pieces) == 1:
        return f'"{pieces[0]}"'
    return "\n\t\t" + "\n\t\t".join(f'"{p}"' for p in pieces)


HEAD = """/*

OOTypeEncodings.h

GENERATED by tools/gen-type-encodings.py from tools/type-encodings.tsv. Do not edit: change the data
and rerun the script (--check fails while this file is stale).

The Objective-C type encodings the game's tables carry, as clang's @encode() gave them on main
eae8c876d, the last tree built as Objective-C++ (bead oo-dbz.3, ADR-0056 amendment oo-dbz.3). The
by-name dispatcher classifies a row by its encoding and prints it in its "has no signature a by-name
call can use" log line, and OOShaderUniformTypeFromEncoding compares encodings: both see exactly the
strings they saw. A C++ class's encoding spells its layout as measured then; it is not derived again
when the class changes.

kOOTypeEncoding<T> is the encoding of T; a type that was not measured does not compile. id and SEL,
which C++ has not, are keyed by the tag types OOObjCId and OOObjCSelector.

*/

#pragma once

#include "OOFoundation.h"
#include "OOTypes.h"
#include "OOEntityEnums.h"
#include "OOMaths.h"
#include "ShipEntity.h"
#include "PlayerEntity.h"
#include "StationEntity.h"
#include "GuiDisplayGen.h"
#include "OOColor.h"
#include "OOTexture.h"
#include "OOPolygonSprite.h"
#include "OOEntityHold.h"
#include "oofnd/PList.hpp"
#include <optional>
#include <string>
#include <vector>

template <class T> struct OOTypeEncoding;	// specialised below for each measured type only

struct OOObjCId;		// the key of the Objective-C object type id's encoding
struct OOObjCSelector;	// the key of the Objective-C selector type SEL's encoding

template <class T> inline constexpr const char *kOOTypeEncoding = OOTypeEncoding<T>::value;

"""


def render():
    out = [HEAD]
    for key, names, encoding in data():
        comment = ", ".join(names)
        out.append(f"// {comment}")
        out.append(f"template <> struct OOTypeEncoding<{key}> {{ static constexpr char value[] = {literal(encoding)}; }};")
    out.append("")
    return "\n".join(out)


def probe():
    lines = ['#include "OOFoundation.h"', '#include "OOTypeEncodings.h"', "#include <cstdio>", "", "int main()", "{"]
    for key, names, encoding in data():
        for n in names:
            lines.append(f'\tstd::printf("%s\\t%s\\n", "{n}", @encode({n}));')
    lines += ["\treturn 0;", "}", ""]
    return "\n".join(lines)


def compare(path):
    want = {n: e for key, names, e in data() for n in names}
    got = {}
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        if line:
            n, e = line.split("\t", 1)
            got[n] = e
    bad = sorted(n for n in want if got.get(n) != want[n])
    for n in bad:
        print(f"{n}: measured {got.get(n)!r:.80}, data {want[n]!r:.80}", file=sys.stderr)
    return 1 if bad else 0


def main():
    args = sys.argv[1:]
    if args[:1] == ["--probe"] and len(args) == 2:
        pathlib.Path(args[1]).write_text(probe(), encoding="utf-8", newline="\n")
        return 0
    if args[:1] == ["--compare"] and len(args) == 2:
        return compare(args[1])
    text = render()
    if args == ["--check"]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 tools/gen-type-encodings.py", file=sys.stderr)
            return 1
        return 0
    if args:
        print(__doc__, file=sys.stderr)
        return 2
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(data())} types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
