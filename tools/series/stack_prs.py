"""Write the PR bodies and gh commands for the seriesb 001-028 stack on OoliteProject/oolite.

Run: python3 -I tools/series/stack_prs.py   (from the OoliteMigration root)
Writes body-NNN.md and open-prs.sh to .agent-tmp/upstream-prs/; opens nothing.
The PRs were opened once (2026-11-14, #799 to #826). After a rebase, refresh a body with
`gh pr edit <n> -R OoliteProject/oolite --body-file .agent-tmp/upstream-prs/body-NNN.md`.
"""
import os, re, shlex, subprocess

ROOT = "/Users/jonms/OoliteMigration"
GAME = f"{ROOT}/oolite-dev"
PRDIR = f"{ROOT}/specs/002-seriesb-rebase-stack/series/pr"
OUT = f"{ROOT}/.agent-tmp/upstream-prs"
os.makedirs(OUT, exist_ok=True)
UP, FORK, ISSUE = "OoliteProject/oolite", "jonmseaman/oolite", 790
PARENT0 = "seriesb/000b-upstream-768-quickjs-only"

files = sorted(f for f in os.listdir(PRDIR) if re.match(r"0(0[1-9]|1\d|2[0-8])-.*\.md$", f))
assert len(files) == 28, files


def git(*args):
    return subprocess.run(["git", "-C", GAME, *args], capture_output=True, text=True, check=True).stdout


def stat(base, head):
    """Files and +/- of base...head, as GitHub's compare view counts them."""
    files = plus = minus = 0
    for line in git("diff", "--numstat", f"{base}...{head}").splitlines():
        a, d, _ = line.split("\t", 2)
        files += 1
        plus += int(a) if a != "-" else 0
        minus += int(d) if d != "-" else 0
    return files, plus, minus


lines = ["#!/usr/bin/env bash", "# Opens the 28 draft PRs bottom-up. Generated by make.py.", "set -euo pipefail",
         f"cd {shlex.quote(OUT)}", ""]
prev = PARENT0
for f in files:
    n, branch = int(f[:3]), f"seriesb/{f[:-3]}"
    text = open(f"{PRDIR}/{f}").read()
    title_line, rest = text.split("\n", 1)
    title = f"[C++ {n:02d}/28] {title_line.removeprefix('# ').strip()}"
    nf, plus, minus = stat(prev, branch)
    url = f"https://github.com/{FORK}/compare/{prev}...{branch}"
    header = (
        f"# {title}\n\n"
        f"> **Step {n} of 28** of the C++ migration (tracking issue #{ISSUE}), on top of #767 and #768.\n>\n"
        f"> **This step's diff:** [`{prev.split('/', 1)[1]}...{branch.split('/', 1)[1]}`]({url})"
        f" — {nf} file{'s' if nf != 1 else ''}, +{plus} / −{minus}.\n>\n"
        f"> GitHub can't stack pull requests across forks, so this PR targets `master` and its own"
        f" Files tab also contains #767, #768 and {'step 1' if n == 2 else f'steps 1–{n - 1}'}." if n > 1 else
        f"# {title}\n\n"
        f"> **Step 1 of 28** of the C++ migration (tracking issue #{ISSUE}), on top of #767 and #768.\n>\n"
        f"> **This step's diff:** [`{prev.split('/', 1)[1]}...{branch.split('/', 1)[1]}`]({url})"
        f" — {nf} file{'s' if nf != 1 else ''}, +{plus} / −{minus}.\n>\n"
        f"> GitHub can't stack pull requests across forks, so this PR targets `master` and its own"
        f" Files tab also contains #767 and #768."
    )
    body = f"{OUT}/body-{n:03d}.md"
    open(body, "w").write(header + "\n" + rest)
    lines.append(f"gh pr create -R {UP} --draft --base master --head jonmseaman:{branch} "
                 f"--title {shlex.quote(title)} --body-file body-{n:03d}.md")
    print(f"{title}  ({nf} files, +{plus}/-{minus})")
    prev = branch

open(f"{OUT}/open-prs.sh", "w").write("\n".join(lines) + "\n")
os.chmod(f"{OUT}/open-prs.sh", 0o755)
